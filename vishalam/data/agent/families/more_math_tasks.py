def _base_str(rng) -> tuple[str, int]:
    b = rng.choice([2, 8, 16, 3, 5])
    n = rng.randint(0, 5000)
    digits = "0123456789ABCDEF"
    s = ""
    while True:
        s = digits[n % b] + s
        n //= b
        if n == 0:
            return s, b


