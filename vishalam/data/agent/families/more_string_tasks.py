def roman(rng) -> str:
    n = rng.randint(1, 3999)
    vals = [(1000, "M"), (900, "CM"), (500, "D"), (400, "CD"), (100, "C"), (90, "XC"), (50, "L"), (40, "XL"),
            (10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")]
    out = ""
    for v, sym in vals:
        while n >= v:
            out += sym
            n -= v
    return out


def ipv4ish(rng) -> str:
    parts = [str(rng.choice([rng.randint(0, 255), rng.randint(0, 300), rng.randint(0, 9)])) for _ in range(rng.choice([3, 4, 4, 4, 5]))]
    if rng.random() < 0.15:
        parts[0] = "0" + parts[0]
    if rng.random() < 0.1:
        parts[-1] = "a"
    return ".".join(parts)


