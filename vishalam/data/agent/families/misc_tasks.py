def nested(rng, depth=0):
    if depth > 3 or rng.random() < 0.35:
        return rng.randint(-9, 9)
    return [nested(rng, depth + 1) for _ in range(rng.randint(0, 3))]


def nested_list(rng):
    return [nested(rng, 1) for _ in range(rng.randint(0, 4))]


def date_str(rng) -> str:
    y = rng.choice([1900, 2000, 2023, 2024, rng.randint(1, 2400)])
    m = rng.randint(0, 13) if rng.random() < 0.2 else rng.randint(1, 12)
    d = rng.randint(0, 32) if rng.random() < 0.2 else rng.randint(1, 31)
    return f"{y:04d}-{m:02d}-{d:02d}" if rng.random() < 0.9 else f"{y}-{m}-{d}"


def valid_date(rng) -> str:
    y = rng.choice([1900, 2000, 2023, 2024, rng.randint(1, 2400)])
    m = rng.randint(1, 12)
    days = [31, 29 if (y % 4 == 0 and y % 100 != 0) or y % 400 == 0 else 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    return f"{y:04d}-{m:02d}-{rng.randint(1, days[m - 1]):02d}"


def version(rng) -> str:
    return ".".join(str(rng.randint(0, 12)) for _ in range(rng.randint(1, 4)))


