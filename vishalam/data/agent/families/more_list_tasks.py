def _without_one(rng) -> list[int]:
    """0..n shuffled, with one number removed."""
    n = rng.randint(1, 9)
    gone = rng.randint(0, n)
    xs = [x for x in range(n + 1) if x != gone]
    rng.shuffle(xs)
    return xs


def sorted_distinct(rng, n=(0, 8)) -> list[int]:
    return sorted(set(ints(rng, -30, 30, n)))


