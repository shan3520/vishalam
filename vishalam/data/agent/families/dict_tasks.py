def int_dict(rng, n=(0, 6), lo=-10, hi=30) -> dict:
    keys = rng.sample(WORDS, rng.randint(*n))
    return {k: rng.randint(lo, hi) for k in keys}


def small_vals_dict(rng, n=(0, 6)) -> dict:
    """Values from a small range so that ties happen."""
    keys = rng.sample(WORDS, rng.randint(*n))
    return {k: rng.randint(0, 5) for k in keys}


def repeated_words(rng, n=(0, 12)) -> list[str]:
    pool = rng.sample(WORDS, 4)
    return [rng.choice(pool) for _ in range(rng.randint(*n))]


